# PR 2: packs export_pr2's frames of a conifer into the game's files content/plants/<key>/tree/, as pack_pr1.py does
# for the broadleaf trees (frames.png, bare.png, look.yaml), with:
#   - `since: 2` (the conifers came with WorldCells.TREE_LOOKS 2: a chunk saved before grows its conifers again) and
#     `rule: fronds` (tree.gdshader lights their leaves as fronds, see export_pr2.py);
#   - the crown's cells from the conifer's shape in its own squash (conifer21.ZS 0.45, not the broadleaf 0.55);
#   - the trunk (cells of log up from the foot) as high as the drawn trunk goes up inside the crown, as the old game's
#     conifers had it (Growth._conifer: up to a tier under the top), not only to the crown's lowest point: a felled
#     conifer gives logs for its whole trunk. Capped by probe_cap (Growth.standing_look's probes must reach over it).
# python3 pack_pr2.py <export dir> <repo> [keys]   (run from tools/art/trees/src/)
import os, sys, math, base64, numpy as np
from PIL import Image
import export_pr2 as E2, pack_pr1 as P1

SINCE = 2


def crown_grid(t, zsq):
    """pack_pr1.crown_grid with the conifer's depth squash."""
    old = P1.ZSQ
    P1.ZSQ = zsq
    try:
        return P1.crown_grid(t)
    finally:
        P1.ZSQ = old


def trunk_cells(t):
    """Cells of log the drawn trunk fills from the foot: its axis's top over the ground, whole cells."""
    tl = t.limbs[0]
    top = max(float(tl.at(u)[1]) for u in np.linspace(0, 1, 41))
    return max(2, int(top / 8.0))


def pack(exp, repo, key):
    import conifer21 as C, render16 as G
    looks = []
    for s in E2.SIZES:
        for v in range(E2.VARIANTS):
            d = np.load(os.path.join(exp, key, '%.2f_%d.npz' % (s, v)))
            fr, bare = d['frames'], d['bare']
            m = ((fr[..., 3] > 0) | (bare > 0)).any(0)
            ys, xs = np.nonzero(m)
            y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
            t = E2.build(key, s, v)
            grid = crown_grid(t, C.ZS)
            cap = P1.probe_cap(grid)
            trunk = trunk_cells(t)
            if cap is not None: trunk = min(trunk, cap)
            looks.append(dict(s=s, v=v, fr=fr[:, y0:y1, x0:x1], bare=bare[:, y0:y1, x0:x1],
                              ax=int(d['ox']) + G.BX - x0, ay=int(d['oy']) - y0, trunk=trunk, cap=cap,
                              grid=grid, ramp=d['ramp'], bark=d['bark'], drawn=trunk_cells(t)))
    for v in range(E2.VARIANTS):
        nxt = None
        for lk in sorted([l for l in looks if l['v'] == v], key=lambda l: -l['s']):
            if nxt is not None and lk['trunk'] >= nxt: lk['trunk'] = nxt - 1
            assert 2 <= lk['trunk'] and (lk['cap'] is None or lk['trunk'] <= lk['cap']), (key, lk['s'], v, lk['trunk'], lk['cap'])
            nxt = lk['trunk']
    W = max(8 * l['fr'].shape[2] for l in looks)
    Ht = sum(l['fr'].shape[1] for l in looks)
    top = np.zeros((Ht, W, 4), np.uint8); bare = np.full((Ht, W, 2), 255, np.uint8)
    y = 0
    for l in looks:
        h, w = l['fr'].shape[1:3]
        for n in range(8):
            top[y:y + h, n * w:(n + 1) * w] = l['fr'][n]
            b = l['bare'][n]
            bits = (b & 0xffff).astype(np.int64)
            bits = np.where(bits == 0xffff, 0xfeff, bits)
            bits = np.where(b > 0, bits, 0xffff)
            bare[y:y + h, n * w:(n + 1) * w, 0] = bits & 255
            bare[y:y + h, n * w:(n + 1) * w, 1] = bits >> 8
        l['x'], l['y'], l['w'], l['h'] = 0, y, w, h
        y += h
    out = os.path.join(repo, 'content', 'plants', key, 'tree')
    os.makedirs(out, exist_ok=True)
    Image.fromarray(top, 'RGBA').save(os.path.join(out, 'frames.png'), optimize=True)
    Image.fromarray(bare, 'LA').save(os.path.join(out, 'bare.png'), optimize=True)
    hx = lambda c: '"#%02x%02x%02x"' % tuple(int(a) for a in c)
    L = ['# The tree drawn from 8 sides (generated by tools/art/trees/src/pack_pr2.py',
         '# from the approved mockup; do not edit by hand). frames.png / bare.png: a row of 8 turns per look; a look:',
         '# its size and variant, cell (x, y, w, h) of turn 0 in px, anchor (ax, ay: the ground under the trunk),',
         '# trunk (cells of log up from the foot), crown (cells of the tree\'s own frame: x0, z0, nx, ny, nz, bits).',
         '# since: the trees\' looks (WorldCells.TREE_LOOKS) these pictures came with; rule: its leaves are fronds.',
         'since: %d' % SINCE,
         'rule: fronds',
         'leaves: [%s]' % ', '.join(hx(c) for c in looks[0]['ramp']),
         'bark: [%s]' % ', '.join(hx(c) for c in looks[0]['bark']),
         'looks:']
    for l in looks:
        x0, z0, nx, ny, nz, bits = l['grid']
        L.append('  - {size: %.2f, variant: %d, x: %d, y: %d, w: %d, h: %d, ax: %d, ay: %d, trunk: %d, crown: [%d, %d, %d, %d, %d, "%s"]}'
                 % (l['s'], l['v'], l['x'], l['y'], l['w'], l['h'], l['ax'], l['ay'], l['trunk'],
                    x0, z0, nx, ny, nz, base64.b64encode(bits).decode()))
    open(os.path.join(out, 'look.yaml'), 'w').write('\n'.join(L) + '\n')
    info = [(l['s'], l['v'], l['w'], l['h'], 'trunk %d (drawn %d, cap %s)' % (l['trunk'], l['drawn'], l['cap']),
             'crown %dx%dx%d' % (l['grid'][2], l['grid'][3], l['grid'][4])) for l in looks]
    return (W, Ht, os.path.getsize(os.path.join(out, 'frames.png')), os.path.getsize(os.path.join(out, 'bare.png'))), info


if __name__ == '__main__':
    exp, repo = sys.argv[1], sys.argv[2]
    keys = sys.argv[3].split(',') if len(sys.argv) > 3 else E2.CONIFERS
    for k in keys:
        if all(os.path.exists(os.path.join(exp, k, '%.2f_%d.npz' % (s, v))) for s in E2.SIZES for v in range(E2.VARIANTS)):
            size, info = pack(exp, repo, k)
            print(k, size, flush=True)
            for i in info: print('   ', *i, flush=True)
        else:
            print(k, 'not exported yet')
