"""Writes the indexes docs/ keeps of what the code and the data hold, and checks the docs
against the repository:

    python3 tools/doc_index.py            writes docs/generated/code-index.md and content-index.md
    python3 tools/doc_index.py --check    fails when either is stale or a doc names a missing file
    python3 tools/doc_index.py uses PATH  prints what loads the script PATH and what it loads

The code index lists every script, shader and tool with the first sentence of its own
description (the first `##` block of a .gd, the first comment of a shader, the docstring of
a .py), by folder, and which folders of src/ load which. The content index lists every mod,
its bundles and their records by kind. Neither keeps line counts or numbers of users, so a
change has to add, move or describe a file, or a record, to make them stale. The check also
reads CLAUDE.md, README.md, docs/ and the mods' READMEs for paths of the repository (a file
or a folder/ under src/, content/... and markdown links) and fails on one that does not exist;
the audit reports under docs/audit/ name the paths of before on purpose and are left out. CI runs --check; run the
script without arguments after adding, moving or describing a file. Run from the repo root.
"""

import os
import re
import subprocess
import sys

CODE_INDEX = "docs/generated/code-index.md"
CONTENT_INDEX = "docs/generated/content-index.md"
CODE_DIRS = ("src/", "tests/", "tools/", "shaders/")
CODE_EXT = (".gd", ".gdshader", ".gdshaderinc", ".py", ".mjs", ".sh")
# Paths the docs name on purpose that do not exist: folders the plans promise.
MISSING_OK = {"src/server/"}
PATH = re.compile(r"(?<![\w/.-])((?:src|tools|tests|shaders|content|assets|scenes|docs|\.github)/[A-Za-z0-9_./-]*)")
LINK = re.compile(r"\]\(([^)\s#]+)(?:#[^)]*)?\)")
LOAD = re.compile(r'(?:preload|load|extends)\s*\(?\s*"res://([^"]+\.gd)"')
SENTENCE = 200


def tracked() -> list:
    # New files count before they are committed; ignored ones (caches, builds) never do.
    out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"],
                         capture_output=True, text=True, check=True).stdout
    return sorted({p for p in out.splitlines() if os.path.exists(p)})


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def first_sentence(text: str) -> str:
    text = " ".join(text.split())
    # A sentence ends at a stop before a capital letter or the end, not at `--path .`.
    m = re.search(r"[.!?](?=\s+[A-ZА-ЯЁ(\"'`]|$)", text)
    if m:
        text = text[:m.start() + 1]
    if len(text) > SENTENCE:
        text = text[:SENTENCE].rsplit(" ", 1)[0] + "…"
    return text.replace("|", "\\|")


def describe(path: str) -> str:
    lines = read(path).splitlines()
    block = []
    if path.endswith(".gd"):
        for line in lines:
            if line.startswith("##"):
                block.append(line[2:].strip())
            elif block:
                break
    elif path.endswith((".gdshader", ".gdshaderinc", ".mjs")):
        for line in lines:
            s = line.strip()
            if s.startswith("//"):
                block.append(s[2:].strip())
            elif block or (s and not s.startswith("shader_type") and not s.startswith("render_mode")):
                break
    elif path.endswith(".py"):
        m = re.search(r'"""(.*?)(?:"""|\n\n)', read(path), re.DOTALL)
        if m:
            block = [m.group(1)]
    elif path.endswith(".sh"):
        for line in lines[1:]:
            if line.startswith("#"):
                block.append(line[1:].strip())
            elif block:
                break
    return first_sentence(" ".join(block)) if block else "(no description)"


def folder(path: str) -> str:
    parts = path.split("/")
    return "/".join(parts[:3] if parts[0] == "src" and len(parts) > 3 else parts[:-1])


def loads(files: list) -> dict:
    edges = {}
    for f in files:
        if f.endswith(".gd"):
            edges[f] = sorted(set(LOAD.findall(read(f))))
    return edges


def code_index(files: list) -> str:
    code = sorted(f for f in files if f.startswith(CODE_DIRS) and f.endswith(CODE_EXT))
    out = ["# Code index", "", "Generated by `python3 tools/doc_index.py`; do not edit. Each script with the first",
           "sentence of its own description. Who loads a script: `python3 tools/doc_index.py uses <path>`.", ""]
    current = None
    for f in code:
        d = folder(f)
        if d != current:
            out += ["", "## " + d, ""]
            current = d
        out.append("- `%s`: %s" % (f, describe(f)))
    out += ["", "## Folders of src/ and what they load", "",
            "| Folder | Loads scripts from |", "|---|---|"]
    by_folder = {}
    for a, bs in loads(files).items():
        if not a.startswith("src/"):
            continue
        for b in bs:
            if b.startswith("src/") and folder(b) != folder(a):
                by_folder.setdefault(folder(a), set()).add(folder(b))
    for d in sorted({folder(f) for f in code if f.startswith("src/")}):
        out.append("| `%s` | %s |" % (d, ", ".join("`%s`" % b for b in sorted(by_folder.get(d, []))) or "—"))
    return "\n".join(out).replace("\n\n\n", "\n\n") + "\n"


def manifest_title(path: str) -> str:
    m = re.search(r"^title:\s*(.+?)\s*$", read(path), re.MULTILINE)
    return m.group(1).strip("\"'") if m else ""


def records(path: str) -> list:
    out = []
    for block in re.split(r"(?m)^(?=- id:)", read(path)):
        m = re.match(r"- id:\s*(\S+)", block)
        if not m:
            continue
        title = re.search(r"(?m)^  title:\s*(.+?)\s*$", block)
        patch = re.search(r"(?m)^  patch:\s*true\s*$", block)
        name = m.group(1) + (" (" + title.group(1).strip("\"'") + ")" if title else "")
        out.append(name + (" — patch" if patch else ""))
    return out


def content_index(files: list) -> str:
    mods = sorted({f.split("/")[1] for f in files if f.startswith("content/") and f.endswith("/mod.yaml")},
                  key=lambda m: (m != "core", m))
    out = ["# Content index", "", "Generated by `python3 tools/doc_index.py`; do not edit. Every mod, its bundles",
           "(a mod without bundle folders is one bundle) and their records by kind, as `id (title)`."]
    for mod in mods:
        out += ["", "## %s: %s" % (mod, manifest_title("content/%s/mod.yaml" % mod)), ""]
        bundles = sorted({f.split("/")[2] for f in files if re.match(r"content/%s/[^/]+/bundle\.yaml$" % mod, f)})
        roots = [("content/%s" % mod, mod, "")] if not bundles else \
            [("content/%s/%s" % (mod, b), "%s/%s" % (mod, b), manifest_title("content/%s/%s/bundle.yaml" % (mod, b)))
             for b in bundles]
        for root, bid, title in roots:
            kinds = sorted(f for f in files if re.match(re.escape(root) + r"/data/[^/]+\.yaml$", f))
            parts = []
            for k in kinds:
                recs = records(k)
                if recs:
                    parts.append("%s: %s" % (os.path.basename(k)[:-5], "; ".join(recs)))
            head = "- `%s`%s" % (bid, " " + title if title else "")
            out.append(head + (": " + ". ".join(parts) if parts else ""))
    return "\n".join(out) + "\n"


def docs(files: list) -> list:
    return [f for f in files if f.endswith(".md") and not f.startswith(("docs/audit/", "docs/generated/"))
            and (f in ("CLAUDE.md", "README.md") or f.startswith("docs/") or re.match(r"content/.*README\.md$", f))]


def broken_paths(files: list) -> list:
    out = []
    for doc in docs(files):
        for n, line in enumerate(read(doc).splitlines(), 1):
            for p in PATH.findall(line.replace("res://", " ")):
                p = re.sub(r":[\d-]+$", "", p.rstrip(".,;)"))
                # A file (a dot in its name) or a folder (a slash at the end): `tools/torch` is a bundle.
                named = p.endswith("/") or "." in p.rsplit("/", 1)[-1]
                if not named or any(c in p for c in "<>*{}%") or p in MISSING_OK:
                    continue
                if not os.path.exists(p):
                    out.append("%s:%d: no `%s`" % (doc, n, p))
            for link in LINK.findall(line):
                if re.match(r"[a-z]+:", link):
                    continue
                target = os.path.normpath(os.path.join(os.path.dirname(doc), link))
                if not os.path.exists(target):
                    out.append("%s:%d: broken link `%s`" % (doc, n, link))
    return out


def uses(path: str, files: list) -> None:
    edges = loads(files)
    print("%s loads:" % path)
    for b in edges.get(path, []):
        print("  " + b)
    print("loaded by:")
    for a, bs in sorted(edges.items()):
        if path in bs:
            print("  " + a)


def main() -> None:
    files = tracked()
    if len(sys.argv) > 2 and sys.argv[1] == "uses":
        uses(sys.argv[2], files)
        return
    wanted = {CODE_INDEX: code_index(files), CONTENT_INDEX: content_index(files)}
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        problems = ["%s is stale: run python3 tools/doc_index.py" % p for p, text in wanted.items()
                    if not os.path.exists(p) or read(p) != text]
        problems += broken_paths(files)
        for p in problems:
            print(p)
        print("docs: %d problems" % len(problems) if problems else "docs OK")
        sys.exit(1 if problems else 0)
    os.makedirs(os.path.dirname(CODE_INDEX), exist_ok=True)
    for p, text in wanted.items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote " + p)


if __name__ == "__main__":
    main()
